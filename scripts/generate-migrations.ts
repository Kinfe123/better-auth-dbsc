/**
 * Writes the SQL this plugin adds on top of a Better Auth schema, for SQLite.
 * It migrates a scratch database without the plugin, then diffs with the plugin on.
 */
import { writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import type { BetterAuthOptions } from "better-auth";
import { getMigrations } from "better-auth/db/migration";
import { dbsc } from "../src/index.ts";

const database = new DatabaseSync(":memory:");
const base = {
  database,
  secret: "x".repeat(32),
  baseURL: "http://localhost:3000",
} satisfies BetterAuthOptions;

await (await getMigrations(base)).runMigrations();
const sql = await (await getMigrations({ ...base, plugins: [dbsc()] })).compileMigrations();

const out = new URL("../migrations/sqlite/0001_dbsc_session.sql", import.meta.url);
writeFileSync(
  out,
  `-- Generated by scripts/generate-migrations.ts. Do not edit by hand.\n${sql.trim()}\n`,
);
console.log(sql.trim());
